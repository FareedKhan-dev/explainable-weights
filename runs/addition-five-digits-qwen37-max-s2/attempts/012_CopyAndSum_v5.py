def write_weights(model: SimpleTransformer, task) -> None:
    """Implement addition using attention and MLP.
    
    Strategy:
    - Encode digit values in embeddings
    - Use attention to copy digit pairs to answer positions
    - Use MLP to compute sum mod 10 with carry
    """
    d = model.d_model
    H = model.n_heads
    dh = d // H
    
    # Zero all parameters
    for p in model.parameters():
        p.data.zero_()
    
    # Token embedding: encode digit value in dim 0
    for i in range(10):
        model.token_emb.weight.data[i, 0] = float(i)
    
    # Position embedding: encode position in dim 1
    for p in range(model.max_seq_len):
        model.pos_emb.weight.data[p, 1] = float(p)
    
    # LayerNorm: identity
    for block in model.blocks:
        block.ln1.weight.data.fill_(1.0)
        block.ln2.weight.data.fill_(1.0)
    model.final_ln.weight.data.fill_(1.0)
    
    # Block 0: Copy first number digits to answer positions
    block0 = model.blocks[0]
    for h in range(H):
        # Query: position 12+i looks for position i
        block0.attn.W_q.weight.data[h*dh, 1] = 1.0  # read position
        
        # Key: advertise position
        block0.attn.W_k.weight.data[h*dh, 1] = 1.0
        
        # Value: extract digit value
        block0.attn.W_v.weight.data[h*dh, 0] = 1.0
        
        # Output: write to dim 10+h
        if 10 + h < d:
            block0.attn.W_o.weight.data[10 + h, h*dh] = 1.0
    
    # Block 1: Copy second number digits to answer positions
    block1 = model.blocks[1]
    for h in range(H):
        # Query: position 12+i looks for position 6+i
        block1.attn.W_q.weight.data[h*dh, 1] = 1.0
        
        # Key: advertise position
        block1.attn.W_k.weight.data[h*dh, 1] = 1.0
        
        # Value: extract digit value
        block1.attn.W_v.weight.data[h*dh, 0] = 1.0
        
        # Output: write to dim 20+h
        if 20 + h < d:
            block1.attn.W_o.weight.data[20 + h, h*dh] = 1.0
    
    # Output head: sum the two digits and output mod 10
    # This is a simple linear approximation
    for digit_out in range(10):
        # Add contributions from both copied digits
        for h in range(H):
            if 10 + h < d and 20 + h < d:
                # Weight for first digit
                model.head.weight.data[digit_out, 10 + h] = 0.5
                # Weight for second digit
                model.head.weight.data[digit_out, 20 + h] = 0.5


model_shorthand_name = "CopyAndSum_v5"
model_description = "Copy digit pairs from input to answer positions using attention, then sum with linear output head."


