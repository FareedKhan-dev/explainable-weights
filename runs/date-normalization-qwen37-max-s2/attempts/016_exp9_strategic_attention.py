# Weight assignment
# ---------------------------------------------------------------------------

def write_weights(model: SimpleTransformer, task) -> None:
    """Attempt 9: Strategic attention patterns for date parsing."""
    torch.manual_seed(456)
    
    d = model.d_model
    V = model.vocab_size
    
    with torch.no_grad():
        # Token embeddings - use random init with scaling
        nn.init.normal_(model.token_emb.weight, mean=0.0, std=0.1)
        
        # Position embeddings - sinusoidal
        model.pos_emb.weight.zero_()
        for pos in range(model.max_seq_len):
            for j in range(0, min(d, 64), 2):
                model.pos_emb.weight[pos, j] = math.sin(pos / (10000 ** (j / d)))
                if j + 1 < d:
                    model.pos_emb.weight[pos, j + 1] = math.cos(pos / (10000 ** (j / d)))
        
        # Attention blocks with varied patterns
        for layer_idx, block in enumerate(model.blocks):
            # Attention - different heads look at different offsets
            nn.init.xavier_uniform_(block.attn.W_q.weight)
            nn.init.xavier_uniform_(block.attn.W_k.weight)
            nn.init.xavier_uniform_(block.attn.W_v.weight)
            nn.init.xavier_uniform_(block.attn.W_o.weight)
            
            # Add some structure: make heads attend to different relative positions
            n_heads = block.attn.n_heads
            d_head = block.attn.d_head
            
            for h in range(n_heads):
                start = h * d_head
                end = start + d_head
                
                # Bias each head toward a different relative position
                offset = h - n_heads // 2  # Range from -4 to +3 for 8 heads
                for i in range(start, min(end, d)):
                    if offset >= 0:
                        # Look forward
                        block.attn.W_q.weight[i, i] += 0.5
                        if i + offset < d:
                            block.attn.W_k.weight[i + offset, i] += 0.5
                    else:
                        # Look backward
                        if i + offset >= 0:
                            block.attn.W_q.weight[i, i + offset] += 0.5
                        block.attn.W_k.weight[i, i] += 0.5
            
            # MLP - standard init
            nn.init.kaiming_uniform_(block.mlp.fc1.weight, nonlinearity='relu')
            nn.init.zeros_(block.mlp.fc1.bias)
            nn.init.xavier_uniform_(block.mlp.fc2.weight)
            nn.init.zeros_(block.mlp.fc2.bias)
        
        # Output head
        nn.init.xavier_uniform_(model.head.weight)


model_shorthand_name = "exp9-strategic-attention"
model_description = "Strategic attention patterns with offset-based heads"


