"""results/data_card.py: a data card for every set the study scores on, with the leakage checks a reviewer would ask for.

    <paper .venv python> data_card.py

For each problem: where its examples come from, the visible, hidden and extra sets with their seeds and sizes, and how
many hidden examples also occur in the visible set (the agent saw the visible set). For TREC, the real-world dataset:
its source and revision, the SHA-256 of the cached files, the split sizes, the label balance and majority-class
accuracy of every set, and exact-duplicate checks between the questions the agent could see (its 2,000-question pool)
and the hidden and official test sets. Writes results/data_card.json.
"""
import hashlib
import json
import os
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
WS = HERE.parent.parent
os.environ.setdefault("WSP_PAPER", str(WS / "weight-space-programming-autoresearch"))
os.environ.setdefault("WSP_HF_HOME", str(Path(__file__).resolve().parents[1] / ".hfh"))
sys.path.insert(0, str(HERE.parent))
from wsp import networks, verify  # noqa: E402

GENERATED = ["word-reversal-3x3", "addition-five-digits", "gcd-three-digits", "date-normalization"]
LABELS = {"0": "ABBR", "1": "ENTY", "2": "DESC", "3": "HUM", "4": "LOC", "5": "NUM"}
SNAPSHOT = "65752bf53af25bc935a0dce92fb5b6c930728450"


def balance(labels):
    c = Counter(labels)
    top, n = c.most_common(1)[0], len(labels)
    return dict(n=n, labels={LABELS[k]: c[k] for k in sorted(c)}, majority=LABELS[top[0]], majority_accuracy=top[1] / n)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    tasks, _ = networks.paper_code()
    card = dict(provisional=False, problems={})
    for name in GENERATED:
        t = tasks.get_task(name)
        vis = {e.prompt for e in t.generate_examples(200, seed=0)}
        hid = [e.prompt for e in t.generate_examples(verify.HIDDEN_N, seed=verify.HIDDEN_SEED)]
        ext = [e.prompt for e in t.generate_examples(verify.EXTRA_N, seed=verify.EXTRA_SEED)]
        card["problems"][name] = dict(
            source=f"generated by the paper's {type(t).__name__} (experiments/evolve/src/task.py)",
            visible=dict(n=200, seed=0), hidden=dict(n=len(hid), seed=verify.HIDDEN_SEED),
            extra=dict(n=len(ext), seed=verify.EXTRA_SEED),
            hidden_also_visible=sum(p in vis for p in hid), extra_also_visible=sum(p in vis for p in ext),
            distinct_hidden=len(set(hid)))
        print(name, card["problems"][name], flush=True)

    hub = Path(__file__).resolve().parents[1] / ".hfh" / "hub" / "datasets--CogComp--trec" / "snapshots" / SNAPSHOT / "default"
    train, test = verify.trec_rows("train"), verify.trec_rows("test")
    pool, rest, hidden = train[:2000], train[2000:], verify.trec_hidden()
    seen = {p for p, _ in pool}
    t = tasks.get_task("trec-coarse")
    visible = [(e.prompt, e.answer) for e in t.generate_examples(200, seed=0)]
    card["problems"]["trec-coarse"] = dict(
        source="TREC question classification, coarse labels (Li and Roth, 2002), dataset CogComp/trec on the "
               "Hugging Face Hub, parquet conversion (revision refs/convert/parquet)",
        snapshot=SNAPSHOT, license="UNVERIFIED: not stated in the local copy; check the dataset card before publishing",
        files={f"{s}/0000.parquet": sha(hub / s / "0000.parquet") for s in ("train", "test")},
        splits=dict(train=len(train), test=len(test)),
        cleaning="lowercased, characters outside a-z, space and apostrophe become spaces, cut or padded to 80 "
                 "with '_' (the task's own _clean_text), then '='",
        pool=dict(what="the first 2,000 training questions: every example the agent's evaluator can draw", **balance([a for _, a in pool])),
        visible=dict(what="200 drawn from the pool with seed 0", **balance([a for _, a in visible])),
        hidden=dict(what="2,000 training questions outside the pool, sampled with seed 1 (the paper's eval_program.py)",
                    **balance([a for _, a in hidden])),
        official_test=dict(what="the official 500-question test split, never loaded during a run", **balance([a for _, a in test])),
        leakage=dict(
            hidden_questions_in_pool=sum(p in seen for p, _ in hidden),
            test_questions_in_pool=sum(p in seen for p, _ in test),
            test_questions_in_hidden=sum(p in {q for q, _ in hidden} for p, _ in test),
            test_questions_anywhere_in_train=sum(p in {q for q, _ in train} for p, _ in test),
            note="exact matches after the task's cleaning; a match is the same question text, not a leak by itself"),
        rest_outside_pool=len(rest))
    print("trec-coarse", json.dumps(card["problems"]["trec-coarse"], indent=1)[:2500], flush=True)
    (HERE / "data_card.json").write_text(json.dumps(card, indent=1) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
